"""Take the function names of the God Hand decomp (LucasPicoli/god-hand-decomp, config/symbol_addrs.txt) into this port.

    python -I tools/symbols/import_decomp_names.py <god-hand-decomp checkout or its config/symbol_addrs.txt>

Updates
- recomp/godhand_functions.csv: the Name of every row the decomp names (func_XXXXXXXX rows get the decomp's name; a row
  already named keeps its name unless the decomp's is different and not an auto name). The boundaries never change.
  The recompiler names the generated functions after this column (<name>_0x<address>), so after "build.py generate"
  the crash log, the hang dump and the PDB read as cPlCamera_update_0x139fa8 instead of func_00139FA8_0x139fa8.
- src/godhand/godhand_function_names.inc: every named function's range, for the run-time lookup (guest_symbols.h)
  that the call profiler and the PC sampler print.

Prints what changed. Standard library only. The decomp's names are the work of the decomp's authors (see its
repository); this script copies the names of functions only, no code.
"""
import csv
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CSV = os.path.join(ROOT, "recomp", "godhand_functions.csv")
INC = os.path.join(ROOT, "src", "godhand", "godhand_function_names.inc")
AUTO = re.compile(r"^(func_[0-9A-Fa-f]{8}|Obj[0-9A-F]{4}_|FUN_|LAB_|entry_)")


def read_symbols(path):
    """{address: name} of the decomp's functions."""
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\s*(\S+)\s*=\s*0x([0-9A-Fa-f]+)\s*;\s*//(.*)", line)
        if m and "type:func" in m.group(3):
            out[int(m.group(2), 16)] = m.group(1)
    return out


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    src = argv[1]
    head = ""
    if os.path.isdir(src):
        try:
            head = subprocess.run(["git", "-C", src, "log", "-1", "--format=%h %ad", "--date=short"],
                                  capture_output=True, text=True, check=False).stdout.strip()
        except OSError:
            pass
        src = os.path.join(src, "config", "symbol_addrs.txt")
    dec = read_symbols(src)
    rows = list(csv.DictReader(open(CSV, encoding="utf-8", newline="")))
    renamed, named_new, kept = [], 0, 0
    for row in rows:
        start = int(row["Start"], 16)
        name = dec.get(start)
        if not name or AUTO.match(name):
            continue
        if row["Name"] == name:
            continue
        if AUTO.match(row["Name"]):
            named_new += 1
        else:
            renamed.append((start, row["Name"], name))
        row["Name"] = name
    with open(CSV, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["Name", "Start", "End", "Size"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    named = [r for r in rows if not AUTO.match(r["Name"])]
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/symbols/import_decomp_names.py from recomp/godhand_functions.csv - do not edit.\n")
        f.write("// Names of the boot ELF's functions (SLUS_215.03), %d of %d, from the God Hand decomp\n" % (len(named), len(rows)))
        f.write("// (github.com/LucasPicoli/god-hand-decomp%s) and the port's own analysis.\n" % ((", " + head) if head else ""))
        f.write("// X(start, end, name)\n")
        for r in named:
            f.write("X(0x%08Xu, 0x%08Xu, \"%s\")\n" % (int(r["Start"], 16), int(r["End"], 16), r["Name"].replace('"', '\\"')))
    print("decomp names %d functions; csv: %d newly named, %d renamed, %d named of %d" % (
        sum(1 for n in dec.values() if not AUTO.match(n)), named_new, len(renamed), len(named), len(rows)))
    for start, old, new in renamed:
        print("  0x%08X %s -> %s" % (start, old, new))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
